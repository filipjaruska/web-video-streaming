import { readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterAll, describe, expect, it } from "vite-plus/test";

import { pickStaticTranscode } from "@/lib/analysisTargets";
import { computeMetrics } from "@/lib/benchmark/metrics";
import {
  toServerProfile,
  type BenchmarkSample,
  type BenchmarkTrace,
  type BenchmarkTraceSummary,
} from "@/lib/benchmark/types";
import { getVideoUrl } from "@/lib/streamingLabels";
import {
  createUploadSession,
  deleteVideo,
  getUploadSession,
  listVideos,
  updateUploadSessionVideo,
  updateVideo,
  uploadSessionFile,
  type UploadSessionResponse,
} from "@/lib/videoApi";
import { getVideoAnalysis } from "@/lib/videoAnalysisApi";
import { getVideoBenchmarks } from "@/lib/videoBenchmarksApi";
import type { VideoTranscodesResponse } from "@/lib/videoTranscodesApi";

import {
  checkAnalysis,
  checkBenchmarks,
  checkDelivery,
  checkSubtitles,
  checkThumbnail,
  checkTranscodes,
  isFullyProcessed,
} from "./support/checks";
import { apiUrl, fetchOk, writesEnabled } from "./support/env";
import { makeClip } from "./support/make-clip";
import { expectSchema, updateVideoResponse, uploadSessionResponse } from "./support/schemas";

/*
 * The write path, end to end: upload a generated clip, wait for the whole pipeline (three packaging
 * runs, both encode grids, VMAF, the derived ladders and their comparison), check the result like
 * any other clip, then submit a benchmark, rename and delete it.
 *
 * Runs only with API_TESTS_WRITE=1 — CI sets it against a throwaway backend. It touches only the
 * video it creates and deletes it at the end, but the pipeline occupies the backend's processing
 * queue for its whole duration (about 9 minutes locally for the 4 s clip).
 */

const CLIP_SECONDS = Number(process.env.E2E_CLIP_SECONDS ?? 4);
const PROCESSING_TIMEOUT_MS = Number(process.env.E2E_TIMEOUT_MINUTES ?? 90) * 60_000;
const POLL_MS = 10_000;

let session: UploadSessionResponse;
let routeId: string;
let transcodes: VideoTranscodesResponse;
let deleted = false;

const statusOf = (body: UploadSessionResponse) => body.session.status.toLowerCase();

// Tests in a file run in order, which these rely on: each step builds on the one before.
describe.skipIf(!writesEnabled)("upload end to end", () => {
  afterAll(async () => {
    // Leave nothing behind, even when a step failed halfway.
    if (routeId && !deleted) {
      await deleteVideo(apiUrl, routeId).catch(() => undefined);
    }
  });

  it("opens an upload session and names the video", async () => {
    session = expectSchema(uploadSessionResponse, await createUploadSession(apiUrl), "new session");
    expect(statusOf(session)).toBe("awaitingupload");
    routeId = session.video.routeId;

    const named = expectSchema(
      uploadSessionResponse,
      await updateUploadSessionVideo(apiUrl, session.sessionId, {
        title: "API e2e clip",
        description: "Generated by tests/api/e2e.upload.test.ts",
      }),
      "named session",
    );
    expect(named.video.title).toBe("API e2e clip");
  });

  it("accepts the clip and queues it", async () => {
    const clipPath = makeClip(join(tmpdir(), `wvs-e2e-${Date.now()}`), CLIP_SECONDS);
    const file = new File([readFileSync(clipPath)], "e2e-clip.mkv", { type: "video/x-matroska" });

    const uploaded = expectSchema(
      uploadSessionResponse,
      await uploadSessionFile(apiUrl, session.sessionId, file),
      "uploaded session",
    );
    expect(["queued", "processing"]).toContain(statusOf(uploaded));
    expect(uploaded.session.uploadedAtUtc).not.toBeNull();
  });

  it(
    "runs the whole processing pipeline to completion",
    async () => {
      const deadline = Date.now() + PROCESSING_TIMEOUT_MS;
      let last = session;
      while (Date.now() < deadline) {
        last = expectSchema(
          uploadSessionResponse,
          await getUploadSession(apiUrl, session.sessionId),
          "session",
        );
        if (["completed", "failed", "expired"].includes(statusOf(last))) {
          break;
        }
        await new Promise((resolve) => setTimeout(resolve, POLL_MS));
      }

      expect(
        statusOf(last),
        `stopped at "${last.session.currentStep}" (${last.session.progressPercent} %)`,
      ).toBe("completed");
      expect(last.session.progressPercent).toBe(100);
      expect(last.session.completedAtUtc).not.toBeNull();
    },
    PROCESSING_TIMEOUT_MS + 60_000,
  );

  it("serves the processed clip like every other clip", async () => {
    expect((await listVideos()).videos.map((video) => video.routeId)).toContain(routeId);

    transcodes = await checkTranscodes(routeId);
    expect(isFullyProcessed(transcodes), "static, dynamic and animation runs all succeeded").toBe(
      true,
    );
    await checkAnalysis(routeId, true);
    await checkBenchmarks(routeId);
    expect(await checkSubtitles(routeId), "the SRT track was extracted").toBeGreaterThan(0);
    await checkThumbnail(routeId);
  });

  it("delivers every packaging run over HLS and DASH, and the source over byte ranges", async () => {
    await checkDelivery(routeId, transcodes);
  });

  it("stores a benchmark run in the shape the runner submits, and aggregates it", async () => {
    const staticRun = transcodes.transcodes.find((run) => run.ladderKind === "static");
    expect(staticRun).toBeDefined();

    const samples: BenchmarkSample[] = [0, 1000, 2000, 3000].map((atMs) => ({
      atMs: atMs + 600,
      playbackSec: atMs / 1000,
      bufferSec: 6,
      bandwidthBps: 18_000_000,
      bitrateBps: 2_500_000,
      rungIndex: 0,
      height: 720,
      droppedFrames: 0,
      totalFrames: 24 * (atMs / 1000 + 1),
    }));
    const trace: BenchmarkTrace = {
      samples,
      events: [
        { kind: "startup", atMs: 600 },
        { kind: "ended", atMs: 4600 },
      ],
      durationMs: 4600,
    };
    const metrics = computeMetrics(trace);

    // Mirrors the body useBenchmarkRunner.ts posts.
    const res = await fetchOk("/api/benchmarks", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        routeId,
        transcodeId: staticRun?.id,
        mode: "Matrix",
        networkProfile: toServerProfile("fourG"),
        ladderKind: "static",
        protocol: "hls",
        abrAlgorithm: "hybrid",
        repetition: 1,
        ...metrics,
        failed: false,
        trace: {
          ...trace,
          summary: {
            resolutionShare: metrics.resolutionShare,
            topRungShare: metrics.topRungShare,
            timeWeightedVmaf: metrics.timeWeightedVmaf,
            avgBufferSec: metrics.avgBufferSec,
            avgThroughputBps: metrics.avgThroughputBps,
            sessionMs: metrics.sessionMs,
          } satisfies BenchmarkTraceSummary,
        },
      }),
    });
    expect(res.status).toBe(201);
    expect(((await res.json()) as { id: string }).id).toMatch(/^[0-9a-f]{32}$/);

    const stored = await getVideoBenchmarks(apiUrl, routeId);
    expect(stored.runs).toHaveLength(1);
    const [aggregate] = stored.aggregates;
    expect(aggregate).toMatchObject({
      networkProfile: "FourG",
      ladderKind: "static",
      protocol: "hls",
      abrAlgorithm: "hybrid",
      runs: 1,
      startupMsMean: metrics.startupMs,
      bufferingRatioMean: metrics.bufferingRatio,
      timeWeightedBitrateBpsMean: metrics.timeWeightedBitrateBps,
    });
    // The per-run figures that travel inside the trace must reach the aggregate too.
    expect(aggregate.sessionMsMean).toBe(metrics.sessionMs);
    expect(aggregate.avgBufferSecMean).toBe(metrics.avgBufferSec);
  });

  it("marks the start of a benchmark run for the variable network's clock", async () => {
    const res = await fetchOk(`/api/benchmarks/runs/api-e2e.${Date.now()}/start`, {
      method: "POST",
    });
    expect(res.status).toBe(204);
  });

  it("renames the published video", async () => {
    const renamed = expectSchema(
      updateVideoResponse,
      await updateVideo(apiUrl, routeId, { title: "API e2e clip (renamed)" }),
      "update response",
    );
    expect(renamed.title).toBe("API e2e clip (renamed)");
    const listed = (await listVideos()).videos.find((video) => video.routeId === routeId);
    expect(listed?.title).toBe("API e2e clip (renamed)");
  });

  it("deletes the video and everything served for it", async () => {
    const staticTarget = pickStaticTranscode((await getVideoAnalysis(apiUrl, routeId)).targets);
    expect(staticTarget).toBeDefined();

    await deleteVideo(apiUrl, routeId);
    deleted = true;

    expect((await listVideos()).videos.map((video) => video.routeId)).not.toContain(routeId);
    for (const path of [
      `/api/videos/${routeId}/transcodes`,
      `/api/videos/${routeId}/analysis`,
      `/api/videos/${routeId}/benchmarks`,
    ]) {
      expect((await fetch(`${apiUrl}${path}`)).status, path).toBe(404);
    }
    expect((await fetch(getVideoUrl("hls", apiUrl, routeId))).status).toBe(404);
    expect((await fetch(getVideoUrl("source", apiUrl, routeId))).status).toBe(404);
  });
});
